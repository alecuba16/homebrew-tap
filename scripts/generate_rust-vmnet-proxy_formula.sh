#!/usr/bin/env bash
# Regenerate Formula/rust-vmnet-proxy.rb from the latest alecuba16/rust-vmnet-proxy
# GitHub release. Reads the published .sha256 sidecar files so the checksums
# never come from a local re-download. Exits non-zero when the release is
# missing any expected platform asset.
#
# Usage: scripts/generate_rust-vmnet-proxy_formula.sh [formula_path] [version]
#   formula_path  default Formula/rust-vmnet-proxy.rb
#   version       default: latest release tag from the GitHub API
set -euo pipefail

REPO="alecuba16/rust-vmnet-proxy"
FORMULA_PATH="${1:-Formula/rust-vmnet-proxy.rb}"
API="https://api.github.com/repos/${REPO}/releases/latest"

AUTH=()
if [[ -n "${GITHUB_TOKEN:-}" ]]; then
  AUTH+=( -H "Authorization: Bearer ${GITHUB_TOKEN}" )
fi

if [[ -n "${2:-}" ]]; then
  TAG="$2"
else
  TAG="$(curl -fsSL -H "Accept: application/vnd.github+json" "${AUTH[@]}" "$API" | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -1)"
fi
[[ -n "$TAG" ]] || { echo "could not resolve latest release tag" >&2; exit 1; }
VERSION="${TAG#v}"
BASE_URL="https://github.com/${REPO}/releases/download/${TAG}"

checksum() {
  local asset="$1"
  local sha_file="${asset}.sha256"
  curl -fsSL "${AUTH[@]}" "${BASE_URL}/${sha_file}" | awk '{print $1}'
}

AARCH64_SHA="$(checksum rust-vmnet-proxy-macos-aarch64.tar.gz)"
X86_64_SHA="$(checksum rust-vmnet-proxy-macos-x86_64.tar.gz)"
[[ -n "$AARCH64_SHA" && -n "$X86_64_SHA" ]] || {
  echo "release ${TAG} is missing one or more .sha256 sidecar files" >&2
  exit 1
}

mkdir -p "$(dirname "$FORMULA_PATH")"
cat > "$FORMULA_PATH" <<EOF
# frozen_string_literal: true

# Generated by scripts/generate_rust-vmnet-proxy_formula.sh in this tap. Do not
# edit by hand; regenerated by the alecuba16/rust-vmnet-proxy release workflow
# and manually after each tagged release.
class RustVmnetProxy < Formula
  desc "Rootless macOS proxy: direct SOCKS5 via bridged socket_vmnet plus supervised SSH tunnels"
  homepage "https://github.com/${REPO}"
  version "${VERSION}"
  license "MIT"

  on_macos do
    on_arm do
      url "${BASE_URL}/rust-vmnet-proxy-macos-aarch64.tar.gz"
      sha256 "${AARCH64_SHA}"

      # Homebrew chdirs into the lone top-level directory in the tarball
      # before install runs.
      def install
        bin.install "rust-vmnet-proxy"
      end
    end
    on_intel do
      url "${BASE_URL}/rust-vmnet-proxy-macos-x86_64.tar.gz"
      sha256 "${X86_64_SHA}"

      def install
        bin.install "rust-vmnet-proxy"
      end
    end
  end

  def caveats
    <<~EOS
      After install, register the launchd service:
        rust-vmnet-proxy install-mac
      Config: ~/.config/rust-vmnet-proxy/config.yaml
      Reference: docs/configuration.md in the repository.
    EOS
  end

  service do
    run [opt_bin/"rust-vmnet-proxy", "--config", "#{Dir.home}/.config/rust-vmnet-proxy/config.yaml"]
    keep_alive true
    log_path "#{Dir.home}/Library/Logs/rust-vmnet-proxy/rust-vmnet-proxy.log"
    error_log_path "#{Dir.home}/Library/Logs/rust-vmnet-proxy/rust-vmnet-proxy.log"
    process_type :background
  end
end
EOF
echo "wrote ${FORMULA_PATH} for ${TAG}"