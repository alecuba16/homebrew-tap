#!/usr/bin/env bash
# Regenerate Formula/herdr-webui.rb from the latest alecuba16/herdr-webui
# GitHub release. Reads the published .sha256 sidecar files so the checksums
# never come from a local re-download. Exits non-zero when the release is
# missing any expected platform asset.
#
# Usage: scripts/generate_formula.sh [formula_path] [version]
#   formula_path  default Formula/herdr-webui.rb
#   version       default: latest release tag from the GitHub API
set -euo pipefail

REPO="alecuba16/herdr-webui"
FORMULA_PATH="${1:-Formula/herdr-webui.rb}"
API="https://api.github.com/repos/${REPO}/releases/latest"

# Anonymous API calls work but rate-limit quickly; use the GITHUB_TOKEN
# env var when it is present (the workflow passes github.token explicitly).
AUTH=()
if [[ -n "${GITHUB_TOKEN:-}" ]]; then
  AUTH+=( -H "Authorization: Bearer ${GITHUB_TOKEN}" )
fi

if [[ -n "${2:-}" ]]; then
  TAG="$2"
else
  TAG="$(curl -fsSL -H "Accept: application/vnd.github+json" "${AUTH[@]}" "$API" | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -1)"
fi
[[ -n "$TAG" ]] || { echo "could not resolve latest release tag" >&2; exit 1; }
VERSION="${TAG#v}"
BASE_URL="https://github.com/${REPO}/releases/download/${TAG}"

checksum() {
  local asset="$1"
  local sha_file="${asset}.sha256"
  curl -fsSL "${AUTH[@]}" "${BASE_URL}/${sha_file}" | awk '{print $1}'
}

AARCH64_SHA="$(checksum herdr-webui-macos-aarch64.tar.gz)"
X86_64_MAC_SHA="$(checksum herdr-webui-macos-x86_64.tar.gz)"
LINUX_SHA="$(checksum herdr-webui-linux-x86_64.tar.gz)"
[[ -n "$AARCH64_SHA" && -n "$X86_64_MAC_SHA" && -n "$LINUX_SHA" ]] || {
  echo "release ${TAG} is missing one or more .sha256 sidecar files" >&2
  exit 1
}

mkdir -p "$(dirname "$FORMULA_PATH")"
cat > "$FORMULA_PATH" <<EOF
# frozen_string_literal: true

# Generated by scripts/generate_formula.sh in this tap. Do not edit by hand;
# regenerated by the alecuba16/herdr-webui release workflow and by this
# tap's daily poll.
class HerdrWebui < Formula
  desc "Web UI and terminal multiplexer for herdr workspaces"
  homepage "https://github.com/${REPO}"
  version "${VERSION}"
  license "AGPL-3.0-or-later"

  on_macos do
    on_arm do
      url "${BASE_URL}/herdr-webui-macos-aarch64.tar.gz"
      sha256 "${AARCH64_SHA}"

      # The tarball wraps both binaries in one top-level directory named
      # after the platform. Homebrew chdirs into a lone top-level directory
      # before install runs, so the paths below are relative to it.
      def install
        bin.install "herdr-webui"
        bin.install "herdr-webui-tui"
      end
    end
    on_intel do
      url "${BASE_URL}/herdr-webui-macos-x86_64.tar.gz"
      sha256 "${X86_64_MAC_SHA}"

      def install
        bin.install "herdr-webui"
        bin.install "herdr-webui-tui"
      end
    end
  end

  on_linux do
    on_intel do
      url "${BASE_URL}/herdr-webui-linux-x86_64.tar.gz"
      sha256 "${LINUX_SHA}"

      def install
        bin.install "herdr-webui"
        bin.install "herdr-webui-tui"
      end
    end
  end

  service do
    run [opt_bin/"herdr-webui"]
    keep_alive true
    log_path var/"log/herdr-webui.log"
    error_log_path var/"log/herdr-webui.err.log"
  end

  def caveats
    <<~EOS
      The web UI serves embedded assets and starts a built-in terminal
      multiplexer backend by default; no other service is needed.

      Start it as a brew-managed background service (launches at login,
      restarts on upgrade):

        brew services start herdr-webui

      Or run it in the foreground for a quick look:

        herdr-webui --https off --backend-mode builtin
        # open http://127.0.0.1:8787

      Settings live in ~/.config/herdr-webui/webui-settings.json
      (bind, TLS, credentials). The service block does not pass flags, so
      configure the bind there if you need something other than the
      default.

      Terminal UI companion: herdr-webui-tui --summary
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/herdr-webui --version")
  end
end
EOF
ruby -c "$FORMULA_PATH" >/dev/null
echo "regenerated ${FORMULA_PATH} at ${VERSION}"
